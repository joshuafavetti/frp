#!/usr/bin/env bash
# Interactively choose how frpc reaches the services it exposes:
#   - host networking (default): services on this machine's 127.0.0.1
#   - app networks: frpc joins other compose apps' Docker networks and
#     reaches containers by service name, with no ports published on the host
# Writes client/compose.override.yaml (gitignored), which compose loads
# automatically. Every change is confirmed first. Option 4 only checks.
#
#   scripts/client-network.sh
set -euo pipefail

cd "$(dirname "$0")/.."
OVR=client/compose.override.yaml
TOML=client/frpc.toml

. scripts/lib.sh

connected_networks() { # networks listed in our generated override
  [[ -f $OVR ]] && sed -nE 's/^    name: (.+)$/\1/p' "$OVR" || true
}

write_override() { # <networks...>; none -> remove override (host networking)
  if (( $# == 0 )); then rm -f "$OVR"; return; fi
  local n
  {
    echo "# Generated by scripts/client-network.sh; re-run it to change."
    echo "# Manual edits are overwritten. frpc leaves host networking and joins"
    echo "# these app networks, reaching containers by service name."
    echo "services:"
    echo "  frpc:"
    echo "    network_mode: !reset null"
    echo "    networks:"
    echo "      - default"
    for n in "$@"; do echo "      - $n"; done
    echo
    echo "networks:"
    for n in "$@"; do
      echo "  $n:"
      echo "    external: true"
      echo "    name: $n"
    done
  } > "$OVR"
}

own_default() { # frpc's own compose default network, e.g. client_default
  local p
  p=$(docker inspect -f '{{index .Config.Labels "com.docker.compose.project"}}' frpc 2>/dev/null || true)
  echo "${p:-client}_default"
}

proxies() { # "name<TAB>localIP" for each active [[proxies]] block (frp's default localIP is 127.0.0.1)
  awk '
    /^[[:space:]]*#/ { next }
    /^[[:space:]]*\[\[/ { if (inp && n != "") print n "\t" ip; inp = /\[\[proxies\]\]/; n = ""; ip = "127.0.0.1"; next }
    inp && /^[[:space:]]*name[[:space:]]*=/    { v = $0; sub(/^[^"]*"/, "", v); sub(/".*/, "", v); n = v }
    inp && /^[[:space:]]*localIP[[:space:]]*=/ { v = $0; sub(/^[^"]*"/, "", v); sub(/".*/, "", v); ip = v }
    END { if (inp && n != "") print n "\t" ip }
  ' "$TOML"
}

active_visitors() { grep -cE '^[[:space:]]*\[\[visitors\]\]' "$TOML" || true; }

dns_names_on() { # <network>: every name that resolves on it (container names, service aliases)
  local c
  for c in $(docker network inspect -f '{{range .Containers}}{{.Name}} {{end}}' "$1"); do
    echo "$c"
    docker inspect -f "{{with index .NetworkSettings.Networks \"$1\"}}{{join .DNSNames \"\n\"}}
{{join .Aliases \"\n\"}}{{end}}" "$c" 2>/dev/null
  done | sed '/^$/d' | sort -u
}

compose_supports_reset() { # "!reset" needs Docker Compose 2.24+
  local v major minor
  v=$(docker compose version --short 2>/dev/null) || return 1
  v=${v#v}; major=${v%%.*}; minor=${v#*.}; minor=${minor%%.*}
  (( major > 2 || (major == 2 && minor >= 24) ))
}

candidates_on() { # <network>: "label<TAB>localIP<TAB>port<TAB>name" per container (not frpc)
  local c svc port
  for c in $(docker network inspect -f '{{range .Containers}}{{.Name}} {{end}}' "$1"); do
    [[ $c == frpc ]] && continue
    svc=$(docker inspect -f '{{index .Config.Labels "com.docker.compose.service"}}' "$c")
    port=$(docker inspect -f '{{range $p, $v := .Config.ExposedPorts}}{{$p}} {{end}}' "$c" | grep -oE '^[0-9]+' || true)
    printf '%s\t%s\t%s\t%s\n' "$c on $1" "${svc:-$c}" "$port" "${svc:-$c}"
  done | sort
}

unique_ips() { # rows on stdin; if a localIP (service name) repeats across networks, use the container name
  awk -F'\t' '{ rows[NR] = $0; split($1, a, " on "); cname[NR] = a[1]; cnt[$2]++ }
    END { for (i = 1; i <= NR; i++) { split(rows[i], f, "\t"); if (cnt[f[2]] > 1) f[2] = cname[i];
          print f[1] "\t" f[2] "\t" f[3] "\t" f[4] } }'
}

add_proxy() { # <default localIP> <default port> <default name>: append one [[proxies]] block
  local name ip port domains d remote block list=""
  local existing; existing=$(proxies | cut -f1)
  while :; do
    ask name "Proxy name" "$3"
    if ! valid_name "$name"; then echo "  ${YELLOW}Use letters, digits, '.', '_' or '-'.${RESET}"; continue; fi
    if grep -qxF "$name" <<< "$existing"; then echo "  ${YELLOW}'$name' is already in $TOML (names must be unique across all clients).${RESET}"; continue; fi
    break
  done
  ask ip "localIP" "$1"
  while :; do
    ask port "localPort" "$2"
    [[ $port =~ ^[0-9]+$ ]] && break; echo "  ${YELLOW}Enter the port the service listens on.${RESET}"
  done
  pick "How should '$name' be reachable?" \
    "http  (website on your domain, via NPM on the server)" \
    "stcp  (private, only through a visitor with the shared secret)" \
    "tcp  (a public port on the server)"
  block="[[proxies]]
name      = \"$name\""
  case $PICKED in
    http*)
      ask domains "Domain(s), comma-separated (e.g. ha.example.com)"
      IFS=',' read -ra ds <<< "$domains"
      for d in "${ds[@]}"; do
        d=$(echo "$d" | tr -d '[:space:]')
        [[ -z $d ]] && continue
        [[ $d =~ ^[A-Za-z0-9*.-]+$ ]] || die "invalid domain: '$d'"
        list+="${list:+, }\"$d\""
      done
      [[ -n $list ]] || die "at least one domain is required"
      block+="
type      = \"http\"
localIP   = \"$ip\"
localPort = $port
customDomains = [$list]"
      ;;
    stcp*)
      grep -qE '^FRP_STCP_SECRET=.+' client/.env || note "FRP_STCP_SECRET is empty in client/.env; set it: ${BOLD}openssl rand -hex 32${RESET}"
      block+="
type      = \"stcp\"
secretKey = \"{{ .Envs.FRP_STCP_SECRET }}\"
localIP   = \"$ip\"
localPort = $port"
      ;;
    tcp*)
      while :; do
        ask remote "remotePort on the server (within its allowPorts, default 6000-6009)"
        [[ $remote =~ ^[0-9]+$ ]] && break; echo "  ${YELLOW}Enter a port number.${RESET}"
      done
      block+="
type       = \"tcp\"
localIP    = \"$ip\"
localPort  = $port
remotePort = $remote"
      ;;
  esac
  [[ $PICKED == tcp* ]] && block=${block/name      =/name       =}   # align with remotePort
  echo
  code <<< "$block"
  echo
  if ask_yn "Append this to $TOML?" y; then
    printf '\n%s\n' "$block" >> "$TOML"   # append in place: keeps the bind-mounted file's inode
    info "Added proxy '$name'."
    case $PICKED in
      http*) next "On the server: add an NPM proxy host for ${BOLD}${list//\"/}${RESET} ${ARROW} http://frps:8080 (websockets on if the app needs it)" ;;
      tcp*)  next "On the server: publish ${BOLD}\"$remote:$remote\"${RESET} in server/compose.yaml and open it in the firewall" ;;
      stcp*) next "On the visitor: add a [[visitors]] block with ${BOLD}serverName = \"$name\"${RESET} and the same FRP_STCP_SECRET" ;;
    esac
    return 0
  fi
  return 1
}

add_services() { # <rows...> "label<TAB>localIP<TAB>port<TAB>name"; returns 0 if anything was added
  local other="A service not listed (enter details myself)" done_opt="Done adding services" added=0 row
  local labels=() r
  for r in "$@"; do labels+=("${r%%$'\t'*}"); done
  while :; do
    section "Services"
    if (( added )); then
      pick "Add another service?" "$done_opt" "${labels[@]}" "$other"
    else
      pick "Which service do you want to expose?" "${labels[@]}" "$other" "$done_opt"
    fi
    [[ $PICKED == "$done_opt" ]] && break
    row=""
    for r in "$@"; do [[ ${r%%$'\t'*} == "$PICKED" ]] && row=$r; done
    if [[ -n $row ]]; then
      IFS=$'\t' read -r _ ip port name <<< "$row"
    else
      ip=$DEFAULT_IP; port=""; name="myservice"
    fi
    add_proxy "$ip" "$port" "$name" && added=1
  done
  (( added ))
}

recreate_and_check() {
  echo
  if ask_yn "Recreate frpc now and check the result?" y; then
    (cd client && docker compose up -d --force-recreate)   # also re-reads frpc.toml
    hint "(waiting a few seconds for frpc to log in...)"
    sleep 5
    checks || exit 1
    echo
    info "Done."
  else
    next "Apply later: ${BOLD}(cd client && docker compose up -d --force-recreate)${RESET}, then choose ${BOLD}5) Check${RESET}"
  fi
}

# ---------- check ----------
check() {
  local mode nets want n ip name status found_on is_addr login names=""

  if [[ $(docker inspect -f '{{.State.Running}}' frpc 2>/dev/null) != true ]]; then
    bad "frpc isn't running. Start it: ${BOLD}(cd client && docker compose up -d)${RESET}"
    return
  fi
  mode=$(docker inspect -f '{{.HostConfig.NetworkMode}}' frpc)
  nets=$(container_networks frpc | paste -sd' ')
  mapfile -t want < <(connected_networks)

  if (( ${#want[@]} == 0 )); then
    if [[ $mode == host ]]; then
      ok "Host networking (default): proxies reach services on this machine's 127.0.0.1"
    else
      bad "No app networks configured, but frpc isn't in host mode. Recreate it: (cd client && docker compose up -d)"
    fi
  else
    if [[ $mode == host ]]; then
      bad "$OVR lists app networks, but frpc is still in host mode. Recreate it: (cd client && docker compose up -d)"
    else
      ok "App-network mode, frpc is on: $nets"
    fi
    for n in "${want[@]}"; do
      if ! docker network inspect "$n" >/dev/null 2>&1; then
        bad "Network $n doesn't exist anymore (is that app running?). Remove it with 3) Disconnect"
      elif [[ " $nets " == *" $n "* ]]; then
        ok "frpc is on $n"
        names+=$'\n'$(dns_names_on "$n" | sed "s/^/$n\t/")   # "network<TAB>name"
      else
        bad "frpc isn't on $n yet. Recreate it: (cd client && docker compose up -d)"
      fi
    done
  fi

  login=$(docker logs frpc 2>&1 | grep -E 'login to (the )?server|connect to server error' | tail -1 || true)
  case $login in
    *"login to server success"*) ok "frpc is logged in to the server" ;;
    "")                          warn "frpc hasn't logged in yet (still connecting?)" ;;
    *)                           bad "frpc can't log in to the server: ${login##*] }" ;;
  esac

  while IFS=$'\t' read -r name ip; do
    [[ -n $name ]] || continue
    is_addr=0
    [[ $ip =~ ^[0-9.]+$ || $ip == *:* || $ip == localhost ]] && is_addr=1
    if [[ $mode == host ]]; then
      if (( is_addr )); then
        ok "Proxy '$name' ${ARROW} $ip"
      else
        bad "Proxy '$name' uses localIP=\"$ip\" (a container name), but frpc is on host networking. Use 1) Connect for its app, or localIP=\"127.0.0.1\" with a published port"
      fi
    elif [[ $ip == 127.0.0.1 || $ip == localhost || $ip == ::1 ]]; then
      bad "Proxy '$name' uses localIP=\"$ip\", which is now frpc's own container. Use the app's service name instead"
    elif (( is_addr )); then
      warn "Proxy '$name' uses a fixed IP ($ip). Container IPs change; prefer the service name"
    else
      found_on=$(awk -F'\t' -v x="$ip" '$2 == x {print $1}' <<< "$names" | sort -u | paste -sd' ')
      if [[ -z $found_on ]]; then
        bad "Proxy '$name' ${ARROW} '$ip' doesn't match any container on frpc's networks. Connect its app with 1) Connect, or fix localIP"
      elif [[ $found_on == *" "* ]]; then
        warn "Proxy '$name' ${ARROW} '$ip' exists on several networks ($found_on), so it may hit the wrong app. Use the unique container name instead"
      else
        ok "Proxy '$name' ${ARROW} '$ip' resolves on $found_on"
      fi
    fi
    status=$(docker logs frpc 2>&1 | grep -F "[$name] start" | tail -1 || true)
    case $status in
      *"start proxy success"*) ok "Proxy '$name' registered with the server" ;;
      *"start error"*)         bad "Proxy '$name' was rejected by the server: ${status##*start error: }" ;;
      *)                       warn "Proxy '$name' has no status in frpc's log yet (still connecting?)" ;;
    esac
  done < <(proxies)

  if [[ $mode != host ]] && (( $(active_visitors) )); then
    warn "frpc.toml has [[visitors]]; off host networking, their bindAddr is inside the container"
    warn "and unreachable from this machine. Keep visitor machines on host networking (option 4)."
  fi
}

checks() { run_checks "Checking frpc setup" check; }

# ---------- preflight ----------
docker_preflight
[[ -f client/.env ]] || die "client/.env not found; set up the client first (README Part 2)"
[[ -f $TOML ]] || die "$TOML not found; copy it from client/frpc.toml.example (README Part 2)"

title "frpc: services and networks"
mapfile -t current < <(connected_networks)
if (( ${#current[@]} )); then
  kv "Network mode" "app networks (${current[*]})"
  DEFAULT_IP=""
else
  kv "Network mode" "host networking (default)"
  DEFAULT_IP="127.0.0.1"
fi
n_proxies=$(proxies | wc -l)
kv "Proxies" "$n_proxies$( (( n_proxies )) && echo " ($(proxies | cut -f1 | paste -sd' '))")"
echo
pick "What do you want to do?" \
  "Connect frpc to more app networks (keeps existing ones)" \
  "Add a service (proxy) to frpc.toml (keeps existing ones)" \
  "Disconnect frpc from an app's network" \
  "Back to host networking (default: reach services on 127.0.0.1)" \
  "Check the current setup (changes nothing)"

case $PICKED in
  Check*)
    checks
    ;;

  Add*)
    rows=()
    if (( ${#current[@]} )); then
      for n in "${current[@]}"; do
        docker network inspect "$n" >/dev/null 2>&1 && while IFS= read -r r; do rows+=("$r"); done < <(candidates_on "$n")
      done
      mapfile -t rows < <(printf '%s\n' "${rows[@]}" | sed '/^$/d' | unique_ips)
    else
      while read -r c; do
        [[ $c == frpc ]] && continue
        [[ $(docker inspect -f '{{.HostConfig.NetworkMode}}' "$c") == host ]] || continue
        rows+=("$c (host networking)"$'\t'"127.0.0.1"$'\t'""$'\t'"$c")
      done < <(docker ps --format '{{.Names}}')
      hint "Host networking: services must listen on (or publish a port to) this machine."
      hint "For apps in other compose projects, use 1) Connect instead; no ports need publishing."
    fi
    add_services "${rows[@]}" || { hint "Nothing was added."; exit 0; }
    recreate_and_check
    ;;

  Back*)
    (( ${#current[@]} )) || { info "Already on host networking; nothing to change."; exit 0; }
    section "Planned changes"
    change "$OVR" "remove (leave ${current[*]}; back to host networking)"
    echo
    ask_yn "Apply this change?" y || { hint "Nothing was changed."; exit 0; }
    write_override
    info "Removed $OVR."
    next "Proxies should use ${BOLD}localIP = \"127.0.0.1\"${RESET} again"
    recreate_and_check
    ;;

  Disconnect*)
    (( ${#current[@]} )) || { info "frpc isn't connected to any app network."; exit 0; }
    section "Disconnect"
    pick "Disconnect from which network?" "${current[@]}"
    drop=$PICKED
    keep=()
    for n in "${current[@]}"; do [[ $n == "$drop" ]] || keep+=("$n"); done
    if (( ${#keep[@]} == 0 )); then
      note "That's the last app network, so frpc will return to host networking."
    fi
    note "Proxies pointing at containers on $drop will stop working; remove them from $TOML."
    section "Planned changes"
    change "$OVR" "frpc leaves $drop"
    echo
    ask_yn "Apply this change?" y || { hint "Nothing was changed."; exit 0; }
    write_override "${keep[@]}"
    info "Updated $OVR."
    recreate_and_check
    ;;

  Connect*)
    compose_supports_reset || die "Docker Compose 2.24+ is required (have: $(docker compose version --short 2>/dev/null || echo unknown))"

    # Map each candidate network to the containers on it.
    declare -A on_net=()
    hostmode=()
    skip=" bridge host none $(own_default) ${current[*]} "
    while read -r c; do
      [[ $c == frpc ]] && continue
      if [[ $(docker inspect -f '{{.HostConfig.NetworkMode}}' "$c") == host ]]; then
        hostmode+=("$c"); continue
      fi
      for n in $(container_networks "$c"); do
        [[ $skip == *" $n "* ]] && continue
        on_net[$n]+="${on_net[$n]:+, }$c"
      done
    done < <(docker ps --format '{{.Names}}')

    section "App networks"
    if (( ${#current[@]} )); then
      kv "Kept" "${current[*]}"
    fi
    if (( ${#hostmode[@]} )); then
      hint "  Host-networked containers have no network to join; frpc reaches them on"
      hint "  127.0.0.1 in the default host mode: ${hostmode[*]}"
    fi

    # Pick one or more networks: one per app whose services frpc should expose.
    other="Enter a network name myself"
    done_opt="Done choosing networks"
    if (( ${#on_net[@]} == 0 )); then
      note "No other running app networks found. Start the apps first (docker compose up -d in each folder)."
    fi
    added=()
    while :; do
      options=()
      for n in $(printf '%s\n' "${!on_net[@]}" | sort); do
        [[ " ${added[*]} " == *" $n "* ]] || options+=("$n  (${on_net[$n]})")
      done
      (( ${#options[@]} )) && hint "Running apps' networks:"
      if (( ${#added[@]} )); then
        pick "Add another network?" "$done_opt" "${options[@]}" "$other"
      else
        pick "Which network should frpc join?" "${options[@]}" "$other"
      fi
      [[ $PICKED == "$done_opt" ]] && break
      net=${PICKED%%  (*}
      if [[ $PICKED == "$other" ]]; then read -rp "Network name: " net || die "no input"; fi
      if ! valid_name "$net"; then echo "  ${YELLOW}Invalid network name: '$net'${RESET}"; continue; fi
      if ! docker network inspect "$net" >/dev/null 2>&1; then echo "  ${YELLOW}Network '$net' doesn't exist (docker network ls).${RESET}"; continue; fi
      if [[ " ${current[*]} ${added[*]} " == *" $net "* ]]; then echo "  ${YELLOW}frpc is already on $net.${RESET}"; else added+=("$net"); fi
      echo "  ${GREEN}Selected:${RESET} ${BOLD}${added[*]:-none}${RESET}"
      echo
    done
    (( ${#added[@]} )) || { hint "Nothing selected; nothing was changed."; exit 0; }

    if (( ${#current[@]} == 0 )); then
      note "This moves frpc off host networking. Proxies must then use container names"
      note "for localIP; 127.0.0.1 will mean frpc's own container."
      if (( $(active_visitors) )); then
        note "frpc.toml also has [[visitors]], which won't be reachable from this machine anymore."
      fi
    fi

    section "Planned changes"
    change "$OVR" "frpc joins ${current[*]:+${current[*]} }${BOLD}${added[*]}${RESET}"
    echo
    ask_yn "Apply this change?" y || { hint "Nothing was changed."; exit 0; }
    write_override "${current[@]}" "${added[@]}"
    info "Updated $OVR."

    rows=()
    for n in "${current[@]}" "${added[@]}"; do
      while IFS= read -r r; do rows+=("$r"); done < <(candidates_on "$n")
    done
    mapfile -t rows < <(printf '%s\n' "${rows[@]}" | sed '/^$/d' | unique_ips)
    # Offer only the containers on the newly added networks.
    new_rows=()
    for r in "${rows[@]}"; do
      for n in "${added[@]}"; do [[ ${r%%$'\t'*} == *" on $n" ]] && new_rows+=("$r"); done
    done
    if (( ${#new_rows[@]} )) && ask_yn "Add [[proxies]] for services on ${added[*]} to $TOML now?" y; then
      add_services "${new_rows[@]}" || true
    fi
    recreate_and_check
    ;;
esac
